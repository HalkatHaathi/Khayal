// Builds supabase/seed.sql from the sample catalogue in src/catalog.js. Re-run: node scripts/gen-seed.mjs
// Replace with the real catalogue import once the product spreadsheet arrives.
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';

const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
const { catalog, collections } = await vite.ssrLoadModule('/src/catalog.js');
await vite.close();

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const WAIST = ['28', '30', '32', '34', '36'];
const out = ['-- generated by scripts/gen-seed.mjs: SAMPLE DATA, run on the dev project only. It replaces the whole catalogue.', 'begin;', 'delete from public.collection_products; delete from public.collections; delete from public.products; delete from public.coupons;'];

catalog.forEach((p, i) => {
  out.push(`insert into public.products (slug,name,type,kind,craft,description,price,compare_at,price_from,pants_addon,tone,alt_tone,fit,sort) values (${[
    q(p.slug), q(p.name), q(p.type), q(p.kind), q(p.craft), q(''), p.price, p.was ?? 'null', p.from ? 'true' : 'false',
    p.type === 'Kurtas' ? 4500 : 'null', q(p.tone), q(p.alt), q(p.fit), catalog.length - i,
  ].join(',')});`);
  const sizes = p.type === 'Pants' ? WAIST : p.sizes;
  for (const s of sizes) {
    out.push(`insert into public.product_sizes select id,${q(s)},${p.inStock ? p.left : 0} from public.products where slug=${q(p.slug)};`);
  }
});

const cols = [['aw26', 0], ['viraam', 1], ['best-sellers', 2], ['new-arrivals', 3], ['t-shirts', 4], ['jackets', 5], ['kurtas', 6], ['hoodies', 7], ['shirts', 8], ['bottoms', 9], ['sale', 10], ['women', 11]];
const TYPE_OF = { 't-shirts': 'T-shirts', jackets: 'Jackets', kurtas: 'Kurtas', hoodies: 'Sweatshirts & Hoodies', shirts: 'Shirts', bottoms: 'Pants' };
for (const [slug, sort] of cols) {
  const c = collections[slug];
  out.push(`insert into public.collections (slug,title,type_filter,on_sale,all_products,sort) values (${q(slug)},${q(c.title)},${q(TYPE_OF[slug])},${slug === 'sale'},${slug === 'new-arrivals'},${sort});`);
  if (['aw26', 'viraam', 'best-sellers'].includes(slug)) {
    c.items.forEach((p, k) => out.push(`insert into public.collection_products select ${q(slug)},id,${k} from public.products where slug=${q(p.slug)};`));
  }
}
out.push(`insert into public.coupons (code,percent,min_subtotal,first_order_only) values ('KHAYAL10',10,0,true);`, 'commit;');
writeFileSync('supabase/seed.sql', out.join('\n') + '\n');
console.log(`seed.sql: ${catalog.length} products, ${cols.length} collections`);
